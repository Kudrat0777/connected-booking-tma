/** Подставить {name} и т. п. в строку перевода. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** «1 запись», «2 записи», «5 записей» / «1 booking», «3 bookings» / «3 yozuv». */
export function pluralize(lang: LangCode, n: number, forms: string): string {
  const f = forms.split('|');
  let word: string;
  if (lang === 'ru' && f.length >= 3) {
    const m10 = n % 10, m100 = n % 100;
    word = m10 === 1 && m100 !== 11 ? f[0] : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? f[1] : f[2];
  } else if (lang === 'en' && f.length >= 2) {
    word = n === 1 ? f[0] : f[1];
  } else {
    word = f[0]; // в узбекском после числа существительное не меняется
  }
  return `${n} ${word}`;
}
